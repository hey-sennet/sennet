// Bytes of a built bundle by package (or by src/ folder), from its sourcemap.
// Usage: node bundle.mjs <bundle.js>   (built with `vite build --sourcemap`)
import { createRequire } from "node:module";
import { readFileSync } from "node:fs";

const require = createRequire(new URL("../../frontend/package.json", import.meta.url));
const { SourceMapConsumer } = require("source-map-js");

const file = process.argv[2];
const code = readFileSync(file, "utf8");
const map = new SourceMapConsumer(JSON.parse(readFileSync(file + ".map", "utf8")));
const lines = code.split("\n");

const group = (source) => {
  const modules = source.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
  if (modules) return modules[1];
  const own = source.match(/src\/([^/]+)/);
  return own ? `src/${own[1]}` : source;
};

// Each mapping owns the generated bytes up to the next mapping.
const sizes = new Map();
const mappings = [];
map.eachMapping((m) => mappings.push(m), null, SourceMapConsumer.GENERATED_ORDER);
for (let i = 0; i < mappings.length; i++) {
  const m = mappings[i], next = mappings[i + 1];
  const end = next && next.generatedLine === m.generatedLine ? next.generatedColumn : lines[m.generatedLine - 1].length;
  const key = m.source ? group(m.source) : "(unmapped)";
  sizes.set(key, (sizes.get(key) ?? 0) + Math.max(0, end - m.generatedColumn));
}
const total = code.length;
console.log(`${(total / 1024).toFixed(0)} KB total`);
for (const [name, bytes] of [...sizes].sort((a, b) => b[1] - a[1]).slice(0, 25)) {
  console.log(`${(bytes / 1024).toFixed(1).padStart(7)} KB  ${((bytes / total) * 100).toFixed(1).padStart(5)}%  ${name}`);
}
